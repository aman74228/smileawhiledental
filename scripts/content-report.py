# Regenerates docs/content-gaps.md: the single replacement checklist.
# Reads the built pages (dist/, run `npm run build:preview` first) and src/data/*.json, and lists
# every dummy element: page → element → dummy value → what the client must provide.
# Hand-written context lives in docs/content-gaps.header.md and is prepended.
# Usage: python3 scripts/content-report.py
import html, json, pathlib, re
from collections import OrderedDict

root = pathlib.Path(__file__).resolve().parent.parent
dist = root / 'dist'

PAGE_NAMES = OrderedDict([
    ('index.html', 'Home'), ('our-practice/index.html', 'Our Practice'), ('services/index.html', 'Services hub'),
    ('testimonials/index.html', 'Testimonials'), ('contact/index.html', 'Contact'),
    ('privacy/index.html', 'Privacy policy'), ('terms/index.html', 'Terms of use'), ('404.html', '404'),
])
for p in sorted((dist / 'services').glob('*/index.html')):
    PAGE_NAMES[str(p.relative_to(dist))] = 'Service: ' + p.parent.name.replace('-', ' ').title()

GLOBAL = ('site-footer', 'site-header', 'mobile-menu', 'sticky-cta', 'mega')

def text_of(fragment):
    t = re.sub(r'<script[\s\S]*?</script>|<style[\s\S]*?</style>', '', fragment)
    t = re.sub(r'<[^>]+>', ' ', t)
    return re.sub(r'\s+', ' ', html.unescape(t)).strip()

def element_extent(doc, start, tag):
    """Return the full outer HTML of the element starting at `start` (naive depth match)."""
    if tag in ('img', 'input', 'br', 'source'):
        return doc[start:doc.index('>', start) + 1]
    depth, i = 0, start
    pat = re.compile(rf'<(/?){tag}\b[^>]*>', re.I)
    for m in pat.finditer(doc, start):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return doc[start:m.end()]
    return doc[start:start + 400]

def section_name(doc, pos):
    """Name of the section an element belongs to. Page sections don't nest, so the last
    section/header/footer (or global overlay div) opened before `pos` is the owner."""
    opener = re.compile(r'<(section|header|footer|div)\b([^>]*)>')
    name = '—'
    for m in opener.finditer(doc, 0, pos):
        tag, attrs = m.group(1), m.group(2)
        cls = (re.search(r'class="([^"]*)"', attrs) or [None, ''])[1].split()
        if tag == 'div' and not any(c in ('mobile-menu', 'sticky-cta') for c in cls):
            continue
        ident = (re.search(r'\bid="([^"]+)"', attrs) or [None, None])[1]
        name = ident or (cls[0] if cls else tag)
    return name

rows_by_page = OrderedDict()
global_rows = OrderedDict()
for rel, name in PAGE_NAMES.items():
    f = dist / rel
    if not f.exists(): continue
    doc = f.read_text()
    body = doc[doc.find('<body'):]
    for m in re.finditer(r'<(\w+)([^>]*\bdata-dummy="true"[^>]*)>', body):
        tag, attrs = m.group(1), m.group(2)
        note = html.unescape((re.search(r'data-note="([^"]*)"', attrs) or [None, ''])[1])
        outer = element_extent(body, m.start(), tag)
        val = text_of(outer)
        if tag == 'picture' or 'photo-slot' in attrs:
            alt = re.search(r'(?:alt|aria-label)="([^"]*)"', outer)
            val = f'[image] {html.unescape(alt.group(1)) if alt else ""}'.strip()
        val = (val[:110] + '…') if len(val) > 110 else val
        sec = section_name(body, m.start())
        key = (sec, note, val)
        if sec in GLOBAL or any(g in sec for g in GLOBAL):
            global_rows.setdefault(key, set()).add(name)
        else:
            rows_by_page.setdefault(name, OrderedDict()).setdefault(key, 0)
            rows_by_page[name][key] += 1

def esc(s): return s.replace('|', '\\|')

out = []
header = root / 'docs' / 'content-gaps.header.md'
if header.exists(): out.append(header.read_text().rstrip() + '\n')
out.append('## Replacement checklist (generated)\n')
out.append('_Generated by `python3 scripts/content-report.py` from the built pages. Do not edit below this line by hand; edit the source and regenerate._\n')
out.append('### Global (header, footer, mobile menu, sticky bar: every page)\n')
out.append('| Section | Dummy value | Client must provide |\n|---|---|---|')
for (sec, note, val), pages in global_rows.items():
    out.append(f'| {esc(sec)} | {esc(val)} | {esc(note)} |')
for page, rows in rows_by_page.items():
    out.append(f'\n### {page}\n')
    out.append('| Section | Dummy value | Client must provide |\n|---|---|---|')
    for (sec, note, val), n in rows.items():
        out.append(f'| {esc(sec)} | {esc(val)}{f" (×{n})" if n > 1 else ""} | {esc(note)} |')

out.append('\n### Data files (`"dummy": true`)\n')
out.append('| File | Entry | Dummy value | Client must provide |\n|---|---|---|---|')
def walk(obj, path, file):
    if isinstance(obj, dict):
        if obj.get('dummy') is True:
            label = obj.get('name') or obj.get('title') or obj.get('label') or path
            value = obj.get('value') or obj.get('text') or obj.get('summary') or obj.get('url') or ''
            if isinstance(value, str) and len(value) > 90: value = value[:90] + '…'
            note = obj.get('note') or ('Real copy' if 'text' in obj or 'intro' in obj else 'Confirm / replace')
            out.append(f'| {file} | {esc(str(label))} | {esc(str(value))} | {esc(note)} |')
        for k, v in obj.items():
            if k not in ('faqSchema',): walk(v, f'{path}.{k}', file)
    elif isinstance(obj, list):
        for i, v in enumerate(obj): walk(v, f'{path}[{i}]', file)
for jf in sorted((root / 'src/data').glob('*.json')):
    walk(json.loads(jf.read_text()), jf.stem, jf.name)

total = sum(len(r) for r in rows_by_page.values()) + len(global_rows)
out.append(f'\n_Total distinct on-page dummy items: {total}._\n')
(root / 'docs' / 'content-gaps.md').write_text('\n'.join(out) + '\n')
print(f'wrote docs/content-gaps.md ({total} on-page items across {len(rows_by_page)} pages + global)')
