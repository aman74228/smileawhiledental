// Generates one entry file per service category from src/data/services.json
// (services/<slug>/index.html → src/templates/service.html). Run before every build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { categories } = JSON.parse(fs.readFileSync(path.join(root, 'src/data/services.json'), 'utf8'));
for (const c of categories) {
  const dir = path.join(root, 'services', c.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'),
    `<!-- GENERATED by scripts/gen-pages.mjs from src/data/services.json. Do not edit. -->\n<!-- @page key=service service=${c.slug} -->\n<!-- @include src/templates/service.html -->\n`);
}
console.log(`generated ${categories.length} service pages`);
